const CACHE_NAME = 'elh-pwa-v1';
const STATIC_ASSETS = [
  '/',
  '/index.html',
  '/manifest.webmanifest',
  '/icons/icon-192x192.png',
  '/icons/icon-512x512.png',
  '/icons/apple-touch-icon.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS);
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) {
            return caches.delete(key);
          }
        })
      );
    })
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);

  // For API, Auth, and Dynamic Calls: Network-first
  if (url.pathname.startsWith('/api') || 
      url.pathname.startsWith('/auth') || 
      url.pathname.startsWith('/me') || 
      url.pathname.startsWith('/dashboard') ||
      url.pathname.startsWith('/due-bills') ||
      url.pathname.startsWith('/attendance') ||
      url.pathname.startsWith('/class-routines')) {
    event.respondWith(
      fetch(event.request).catch(() => {
        return caches.match(event.request);
      })
    );
    return;
  }

  // For Static Assets & Navigations: Stale-While-Revalidate
  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      const fetchPromise = fetch(event.request).then((networkResponse) => {
        if (networkResponse && networkResponse.status === 200) {
          const responseToCache = networkResponse.clone();
          caches.open(CACHE_NAME).then((cache) => {
            cache.put(event.request, responseToCache);
          });
        }
        return networkResponse;
      }).catch(() => {
        // If offline and navigating to a page, serve cached index.html SPA shell
        if (event.request.mode === 'navigate') {
          return caches.match('/index.html');
        }
      });
      return cachedResponse || fetchPromise;
    })
  );
});
